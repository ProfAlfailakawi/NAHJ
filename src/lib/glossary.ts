/* ------------------------------------------------ سُلّم الاستقلالية */

export interface LadderStep {
  level: number;
  /** الاسم التقني، كما يظهر في الوثائق. */
  code: string;
  /** ما يعنيه للموظف، بصيغة فعل لا اسم. */
  plain: string;
  /** ماذا يقع عليك أنت عند هذا المستوى. */
  yourPart: string;
}

